        <h2>1. Wie zijn wij?</h2>
        <p>Pizzeria Sole Machina, is verantwoordelijk voor de verwerking van persoonsgegevens zoals beschreven in deze privacyverklaring.</p>

        <h2>2. Welke gegevens verzamelen wij?</h2>
        <p>Bij het plaatsen van een bestelling verwerken wij de volgende gegevens:</p>
        <ul>
            <li>Naam en adres (voor bezorging)</li>
            <li>Betalingsinformatie (verwerkt via onze betaalprovider)</li>
            <li>Bestelgeschiedenis</li>
        </ul>

        <h2>3. Waarvoor gebruiken wij uw gegevens?</h2>
        <p>Uw gegevens worden uitsluitend gebruikt voor:</p>
        <ul>
            <li>Het verwerken en bezorgen van uw bestelling</li>
            <li>Contact bij vragen over uw bestelling</li>
            <li>Het verbeteren van onze dienstverlening</li>
        </ul>

        <h2>4. Delen wij uw gegevens?</h2>
        <p>Wij verkopen uw gegevens nooit aan derden. Gegevens worden alleen gedeeld met onze bezorgpartner, uitsluitend voor de aflevering van uw bestelling.</p>

        <h2>5. Hoe lang bewaren wij uw gegevens?</h2>
        <p>Uw gegevens worden bewaard zolang dit noodzakelijk is voor de doeleinden waarvoor ze zijn verzameld, of zolang de wet dit vereist (maximaal 7 jaar voor financiële gegevens).</p>

        <h2>6. Uw rechten</h2>
        <p>U heeft het recht om uw gegevens in te zien, te corrigeren of te laten verwijderen. Neem hiervoor contact op via <a href="mailto:privacy@bellanapoli.nl">privacy@bellanapoli.nl</a>.</p>

        <h2>7. Vragen?</h2>
        <p>Voor vragen over deze privacyverklaring kunt u ons bereiken via bovenstaand e-mailadres of per post op ons vestigingsadres.</p>
